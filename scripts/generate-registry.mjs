#!/usr/bin/env node
/** Generates screen-registry.csv and docs/ui-screen-registry.md from packages/types (single source of truth). */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
const require = createRequire(import.meta.url);
execSync('pnpm --filter @collabiz/types build', { stdio: 'ignore' });
const { SCREENS, SCREEN_FAMILIES, SCREEN_STATUS, PATTERN_PURPOSE } = require('../packages/types/dist/index.js');

const st = (id) => SCREEN_STATUS[id]?.status ?? 'planned';
const esc = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
const cols = ['id', 'title', 'family', 'stage', 'app', 'route', 'access', 'api_module', 'atlas_layout', 'mobile', 'pattern', 'status', 'tests', 'notes'];
const csv = [cols.join(',')].concat(SCREENS.map((s) => [s.id, s.title, SCREEN_FAMILIES[s.family - 1].name, String(s.stage).padStart(2, '0'), s.app, s.route, s.access, s.apiModule, s.atlasLayout, s.mobile, s.pattern, st(s.id), (SCREEN_STATUS[s.id]?.tests ?? []).join(' '), SCREEN_STATUS[s.id]?.notes ?? ''].map(esc).join(',')));
writeFileSync('screen-registry.csv', csv.join('\n') + '\n');

const count = (x) => SCREENS.filter((s) => st(s.id) === x).length;
let md = `# UI Screen Registry (001–165)\n\n> Generated by \`pnpm registry\` from \`packages/types/src/screens.ts\` + \`screen-status.ts\`. Do not edit by hand.\n\n`;
md += `Source: Master Book Section 05 (functional specification) and the 165-screen UI Design Atlas (U01–U10). Screen IDs and titles are preserved verbatim.\n\n`;
md += `**Status:** verified ${count('verified')} · implemented ${count('implemented')} · scaffolded ${count('scaffolded')} · planned ${count('planned')}\n\n`;
md += `Status meaning: *planned* (not started) → *scaffolded* (route + shell) → *implemented* (wired to real API) → *verified* (automated test passed).\n\n`;
md += `## Purpose patterns (Master Book §5)\n\n` + Object.entries(PATTERN_PURPOSE).map(([k, v]) => `- **${k}** — ${v}`).join('\n') + '\n\n';
md += `All screens share the acceptance rule: *correct role can complete the primary action; unauthorized users cannot; failure and empty states are understandable; audit events are created for consequential changes.*\n\n`;
md += `Mobile column: **native** = dedicated Expo screen; **responsive** = responsive web at 390/360 px; **desktop-admin** = admin portal (1440/1024/768).\n`;
for (const f of SCREEN_FAMILIES) {
  md += `\n## ${String(f.id).padStart(2, '0')} · ${f.name}\n\n| ID | Screen | Stage | App · Route | Access | API module | Atlas | Mobile | Status | Tests |\n|---|---|---|---|---|---|---|---|---|---|\n`;
  for (const s of SCREENS.filter((x) => x.family === f.id)) {
    md += `| ${s.id} | ${s.title} | ${String(s.stage).padStart(2, '0')} | ${s.app} \`${s.route}\` | ${s.access} | ${s.apiModule} | ${s.atlasLayout} | ${s.mobile} | ${st(s.id)} | ${(SCREEN_STATUS[s.id]?.tests ?? []).join('<br>')} |\n`;
  }
}
writeFileSync('docs/ui-screen-registry.md', md);
console.info(`Registry written: verified ${count('verified')}, implemented ${count('implemented')}, planned ${count('planned')}`);
